"""
build_dataset.py
===========================================================================
Step 1 of 4. Build the matched, QC-filtered dataset for the Athena vs. NIAK
pipeline comparison (Chapter 5 of the seminar).

Loads raw connectivity time series for both pipelines and applies a
three-step subject inclusion policy (see Chapter 5.2 and 5.3):

  1. PRIMARY: keep only subjects with an official QC pass for that
     pipeline (QC_Athena == 1 / QC_NIAK == 1 in the phenotypic file).
  2. SUPPLEMENTARY: among QC-passed subjects, drop any subject with more
     than SEVERE_THRESHOLD flat (zero-variance) ROIs -- this catches
     registration failures the official visual QC check missed.
  3. RESIDUAL: for whoever survives steps 1-2, drop any ROI still flat in
     at least one remaining subject, for every subject, so all feature
     vectors in a pipeline end up the same length.

Subjects are then matched across pipelines (kept only if present and
QC-passed in both), and the result is saved to
    output/multisite_data_final.npz
for use by  run_evaluation.py.
"""

from pathlib import Path
from collections import defaultdict
import re

import numpy as np
import pandas as pd
import scipy.io as sio

# ── CONFIG ───────────────────────────────────────────────────────────────
DATA_ROOT = Path("data")            # raw, unmodified pipeline downloads
OUTPUT_ROOT = Path("output")        # files generated by this pipeline

ATHENA_ROOT = DATA_ROOT / "Athena"
NIAK_ROOT = DATA_ROOT / "NIAK"
PHENOTYPIC_TSV = DATA_ROOT / "adhd200_preprocessed_phenotypics.tsv"
OUTPUT_NPZ = OUTPUT_ROOT / "multisite_data_final.npz"

SEVERE_THRESHOLD = 50  # supplementary exclusion cutoff (flat ROI count)

ATHENA_SITE_DIRS = {
    "KKI": "KKI", "NYU": "NYU", "OHSU": "OHSU",
    "Peking_1": "Beijing", "Peking_2": "Beijing", "Peking_3": "Beijing",
    "Pittsburgh": "Pittsburgh", "WashU": "WashU", "NeuroIMAGE": "NeuroIMAGE",
}
NIAK_SITE_DIRS = {
    "KKI": "KKI", "Beijing": "Beijing", "NYU": "NYU", "OHSU": "OHSU",
    "Pittsburgh": "Pittsburgh", "WashU": "WashU", "NeuroIMAGE": "NeuroIMAGE",
}
# ─────────────────────────────────────────────────────────────────────────


def load_labels_and_qc(pheno_path: Path) -> pd.DataFrame:
    """Load subject diagnosis (DX) and per-pipeline QC flags."""
    pheno = pd.read_csv(pheno_path, sep="\t")
    pheno = pheno[["ScanDir ID", "DX", "QC_Athena", "QC_NIAK"]].dropna(subset=["DX"])
    pheno["ScanDir ID"] = (
        pheno["ScanDir ID"].astype(str).str.extract(r"(\d+)")[0].str.zfill(7)
    )
    pheno["DX"] = pd.to_numeric(pheno["DX"], errors="coerce")
    pheno = pheno.dropna(subset=["DX"])  # catches "pending" and any other non-numeric DX values
    pheno["DX"] = pheno["DX"].astype(int)
    return pheno.set_index("ScanDir ID")


def compute_fc_vector(ts: np.ndarray) -> np.ndarray:
    """Pearson correlation matrix -> flattened upper-triangle feature vector."""
    fc_matrix = np.corrcoef(ts, rowvar=False)
    n = fc_matrix.shape[0]
    iu = np.triu_indices(n, k=1)
    return fc_matrix[iu]


# ══════════════════════════════════════════════════════════════════════
# ATHENA
# ══════════════════════════════════════════════════════════════════════

def athena_extract_subject_id(fp: Path) -> str:
    name = fp.stem.replace("sfnwmrda", "")
    return name.split("_")[0].zfill(7)


def athena_get_roi_columns(fp: Path):
    df = pd.read_csv(fp, sep="\t", nrows=0)
    return [c for c in df.columns if c.startswith("Mean_")]


def load_athena_all_sites(labels: pd.DataFrame):
    print("\n" + "=" * 70)
    print("ATHENA")
    print("=" * 70)

    site_files = defaultdict(list)
    for folder_name, logical_site in ATHENA_SITE_DIRS.items():
        files = sorted((ATHENA_ROOT / folder_name).glob(
            "*/sfnwmrda*_session_1_rest_1_cc200_TCs.1D"))
        site_files[logical_site].extend(files)

    all_pairs = [(s, fp) for s, files in site_files.items() for fp in files]
    print(f"Files found: {len(all_pairs)}")

    # Common ROI columns across everyone (structural presence, not variance)
    all_roi_sets = [set(athena_get_roi_columns(fp)) for _, fp in all_pairs]
    common_rois = sorted(set.intersection(*all_roi_sets), key=lambda x: int(x.split("_")[1]))
    print(f"Common ROI columns (structural): {len(common_rois)}")

    # Step 1: apply QC_Athena == 1 filter, track skips
    kept = []
    n_no_label, n_qc_fail = 0, 0
    for site, fp in all_pairs:
        sid = athena_extract_subject_id(fp)
        if sid not in labels.index:
            n_no_label += 1
            continue
        if labels.loc[sid, "QC_Athena"] != 1:
            n_qc_fail += 1
            continue
        kept.append((site, fp, sid))
    print(f"Dropped (no label): {n_no_label}   Dropped (QC_Athena != 1): {n_qc_fail}")
    print(f"Remaining after QC filter: {len(kept)}")

    # Step 2: supplementary check for residual severe flatness among QC-passed subjects
    loaded = []  # (site, sid, ts)
    for site, fp, sid in kept:
        df = pd.read_csv(fp, sep="\t")
        ts = df[common_rois].values
        loaded.append((site, sid, ts))

    severe = []
    for site, sid, ts in loaded:
        stds = ts.std(axis=0)
        n_flat = int((stds == 0).sum())
        if n_flat > SEVERE_THRESHOLD:
            severe.append((sid, site, n_flat))
    if severe:
        print(f"Supplementary exclusion (>{SEVERE_THRESHOLD} flat ROIs despite QC pass): {len(severe)}")
        for sid, site, n in severe:
            print(f"  {sid}  site={site}  flat={n}")
    severe_ids = {sid for sid, _, _ in severe}
    loaded = [(s, sid, ts) for s, sid, ts in loaded if sid not in severe_ids]

    # Step 3: residual ROI exclusion from whoever remains
    bad_roi_idx = set()
    for _, _, ts in loaded:
        stds = ts.std(axis=0)
        bad_roi_idx.update(np.where(stds == 0)[0].tolist())
    bad_roi_idx = sorted(bad_roi_idx)
    print(f"Residual ROI columns still flat in >=1 remaining subject: {len(bad_roi_idx)}")

    final_rois = [r for i, r in enumerate(common_rois) if i not in bad_roi_idx]
    print(f"Final Athena feature space: {len(final_rois)} ROIs "
          f"-> {len(final_rois) * (len(final_rois) - 1) // 2} features")

    X_rows, y_rows, subj_ids, subj_site = [], [], [], []
    keep_col_idx = [i for i in range(len(common_rois)) if i not in bad_roi_idx]
    for site, sid, ts in loaded:
        ts_clean = ts[:, keep_col_idx]
        X_rows.append(compute_fc_vector(ts_clean))
        y_rows.append(labels.loc[sid, "DX"])
        subj_ids.append(sid)
        subj_site.append(site)

    X = np.vstack(X_rows)
    y = np.array(y_rows)
    print(f"Athena FINAL: X={X.shape}, any NaN={np.isnan(X).any()}")
    return X, y, np.array(subj_ids), np.array(subj_site)


